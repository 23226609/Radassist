const ICON_BASE = 'fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"';

function make(tag, children, props = {}) {
  const el = document.createElementNS("http://www.w3.org/2000/svg", tag);
  el.setAttribute("viewBox", "0 0 24 24");
  el.setAttribute("width", props.size || 18);
  el.setAttribute("height", props.size || 18);
  el.setAttribute(ICON_BASE.split("=")[0], ICON_BASE.split("=")[1].replace(/"/g, ""));
  for (const [k, v] of Object.entries(props)) {
    if (k === "size") continue;
    el.setAttribute(k, v);
  }
  for (const child of children) el.appendChild(child);
  return el;
}

function path(d) {
  const p = document.createElementNS("http://www.w3.org/2000/svg", "path");
  p.setAttribute("d", d);
  return p;
}

